import { readFileSync, readdirSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// Scan for .md files sorted alphabetically
const mdFiles = readdirSync(__dirname)
  .filter(f => f.endsWith('.md'))
  .sort();

// Read each file into documents array
const documents = mdFiles.map(filename => ({
  filename,
  content: readFileSync(join(__dirname, filename), 'utf8'),
}));

// Build embedded JavaScript as a string (not template literals) to avoid backtick conflicts
const jsLines = [
  'const DOCUMENTS = ' + JSON.stringify(documents) + ';',
  '',
  'mermaid.initialize({',
  '  startOnLoad: false,',
  "  theme: 'default',",
  "  securityLevel: 'loose',",
  '  flowchart: { htmlLabels: true, curve: \'basis\' },',
  '});',
  '',
  'let currentIndex = -1;',
  '',
  'function populateSidebar() {',
  '  const list = document.getElementById(\'doc-list\');',
  '  DOCUMENTS.forEach(function(doc, i) {',
  '    const btn = document.createElement(\'button\');',
  "    btn.className = 'doc-item';",
  "    btn.textContent = doc.filename.replace(/\\.md$/, '');",
  '    btn.onclick = function() { selectDocument(i); };',
  '    list.appendChild(btn);',
  '  });',
  '}',
  '',
  'function selectDocument(index) {',
  '  currentIndex = index;',
  "  const items = document.querySelectorAll('.doc-item');",
  '  items.forEach(function(item, i) {',
  "    item.classList.toggle('active', i === index);",
  '  });',
  '  renderDocument();',
  '}',
  '',
  'function renderDocument() {',
  '  if (currentIndex < 0 || currentIndex >= DOCUMENTS.length) return;',
  '  const doc = DOCUMENTS[currentIndex];',
  "  const main = document.getElementById('main-content');",
  '  let html = marked.parse(doc.content);',
  '  // Add IDs to headings for TOC linking',
  "  html = html.replace(/<(h[1-4])>(.*?)<\\/\\1>/gi, function(match, tag, text) {",
  "    const id = text.toLowerCase().replace(/<[^>]+>/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');",
  '    return \'<\' + tag + \' id="\' + id + \'">\' + text + \'</\' + tag + \'>\';',
  '  });',
  '  main.innerHTML = \'<div class="content">\' + html + \'</div>\';',
  '  renderMermaidDiagrams();',
  '}',
  '',
  'function renderMermaidDiagrams() {',
  "  const blocks = document.querySelectorAll('code.language-mermaid');",
  '  let diagramIndex = 0;',
  '  blocks.forEach(function(block) {',
  '    const pre = block.parentElement;',
  '    const code = block.textContent;',
  "    const container = document.createElement('div');",
  "    container.className = 'mermaid-container';",
  '    const id = \'mermaid-diagram-\' + diagramIndex++;',
  "    container.id = id;",
  '    pre.parentNode.replaceChild(container, pre);',
  '    mermaid.render(id + \'-svg\', code).then(function(result) {',
  '      container.innerHTML = result.svg;',
  '    }).catch(function(err) {',
  "      const errDiv = document.createElement('div');",
  "      errDiv.className = 'mermaid-error';",
  "      errDiv.innerHTML = '<pre>' + code.replace(/</g, '&lt;').replace(/>/g, '&gt;') + '</pre>';",
  '      container.replaceWith(errDiv);',
  '    });',
  '  });',
  '}',
  '',
  'function toggleToc() {}',
  'function toggleDiagrams() {}',
  'function closeModal() {}',
  '',
  'populateSidebar();',
  'if (DOCUMENTS.length > 0) { selectDocument(0); }',
];

const embeddedJs = jsLines.join('\n');

